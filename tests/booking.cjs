/* Run with Playwright available on NODE_PATH; uses installed Microsoft Edge. */
const { chromium } = require('playwright');
const { execFileSync } = require('node:child_process');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const markup = execFileSync('php', ['-r', `define('ABSPATH', true); function esc_attr($v) { return htmlspecialchars($v, ENT_QUOTES); } function esc_html($v) { return htmlspecialchars($v, ENT_QUOTES); } function checked($a,$b) { if ($a === $b) echo 'checked'; } include 'template-parts/booking/modal.php';`], { cwd: root, encoding: 'utf8' });
(async () => {
    const browser = await chromium.launch({ channel: 'msedge', headless: true });
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = [];
    page.on('pageerror', err => errors.push(err.message));
    await page.setContent(`<button id="trigger" data-nsp-booking data-service-title="Home cleaning" data-service-category="Residential">Book Service</button>${markup}`);
    for (const stylesheet of ['assets/css/bootstrap.min.css', 'assets/css/reset.css', 'assets/css/style.css', 'rtl.css', 'assets/css/booking.css']) await page.addStyleTag({ path: path.join(root, stylesheet) });
    await page.evaluate(() => {
        document.querySelector('#trigger').dataset.packages = JSON.stringify([{ package_name: '<img src=x onerror=alert(1)>', package_price: 499.99, package_description: 'Whole home', package_perk: 'Supplies included' }]);
        window.sent = [];
        window.open = (...args) => window.sent.push(args);
        Object.defineProperty(navigator, 'geolocation', { configurable: true, value: { getCurrentPosition: success => { window.gpsSuccess = success; } } });
    });
    await page.addScriptTag({ path: path.join(root, 'assets/js/booking.js') });
    const next = page.locator('[data-next]');
    await page.click('#trigger');
    assert.equal(await page.locator('dialog').evaluate(el => getComputedStyle(el).textAlign), 'left');
    await next.click();
    assert.match(await page.locator('[data-error]').innerText(), /Choose a package/);
    assert.equal(await page.locator('[data-packages] img').count(), 0, 'Package text must not become HTML');
    await page.check('[name=package]');
    await next.click();
    await next.click();
    assert.match(await page.locator('[data-error]').innerText(), /city/);
    await page.check('[name=city][value=Dammam]');
    await next.click();
    assert.match(await page.locator('[data-error]').innerText(), /street/);
    await page.fill('[name=street]', '12 King Street');
    await page.fill('[name=area]', 'Al Faisaliyah');
    await next.click();
    await page.fill('[name=date]', '2000-01-01');
    await next.click();
    assert.match(await page.locator('[data-error]').innerText(), /future date/);
    await page.fill('[name=date]', '2099-12-31');
    await page.check('[name=time][value="1PM–4PM"]');
    await next.click();
    await page.fill('[name=fullName]', 'Test Customer');
    await page.fill('[name=mobile]', 'bad number');
    await next.click();
    assert.match(await page.locator('[data-error]').innerText(), /valid mobile/);
    await page.fill('[name=mobile]', '+966 559 357 772');
    await page.fill('[name=instructions]', 'Gate #2 & ring bell');
    await next.click();
    assert.match(await page.locator('[data-total]').innerText(), /449\.99/);
    assert.match(await page.locator('[data-discount]').innerText(), /50\.00/);
    const reference = await page.locator('[data-reference]').innerText();
    assert.match(reference, /^NSP-\d{8}-[A-Z0-9]{4}$/);
    if (process.env.BOOKING_SCREENSHOT) await page.screenshot({ path: process.env.BOOKING_SCREENSHOT });
    await page.setViewportSize({ width: 1440, height: 1000 });
    assert.equal(await next.isVisible(), true);
    await page.setViewportSize({ width: 390, height: 844 });
    await page.click('[data-back]');
    assert.equal(await page.inputValue('[name=fullName]'), 'Test Customer');
    await next.click();
    assert.equal(await page.locator('[data-reference]').innerText(), reference);
    await next.click();
    const [url, target, features] = await page.evaluate(() => window.sent[0]);
    const parsed = new URL(url);
    assert.equal(parsed.origin + parsed.pathname, 'https://api.whatsapp.com/send');
    assert.equal(parsed.searchParams.get('phone'), '966559357772');
    assert.match(parsed.searchParams.get('text'), /Gate #2 & ring bell/);
    assert.match(parsed.searchParams.get('text'), /12 King Street, Al Faisaliyah/);
    assert.equal(target, '_blank'); assert.match(features, /noopener/);
    assert.equal(await page.evaluate(() => document.querySelector('dialog').scrollWidth <= document.querySelector('dialog').clientWidth), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#trigger').evaluate(el => el === document.activeElement), true);
    await page.click('#trigger');
    assert.equal(await page.inputValue('[name=fullName]'), '');
    await page.check('[name=package]'); await next.click();
    await page.click('[data-gps]');
    await page.evaluate(() => window.gpsSuccess({ coords: { latitude: 26.4207, longitude: 50.0888 } }));
    assert.equal(await page.locator('[data-address]').isVisible(), false);
    await page.check('[name=city][value=Khobar]'); await next.click();
    assert.match(await page.locator('#nsp-booking-title').innerText(), /schedule/);
    await page.click('[data-back]');
    await page.click('[data-clear-gps]');
    assert.equal(await page.locator('[data-address]').isVisible(), true);
    await page.click('[data-gps]');
    await page.click('[data-close]');
    await page.click('#trigger');
    await page.evaluate(() => window.gpsSuccess({ coords: { latitude: 1, longitude: 2 } }));
    assert.equal(await page.locator('[data-clear-gps]').isVisible(), false);
    await page.click('[data-close]');
    await page.evaluate(() => { document.querySelector('#trigger').dataset.packages = 'invalid-json'; });
    await page.click('#trigger');
    assert.equal(await next.isDisabled(), true);
    assert.match(await page.locator('#nsp-booking [data-packages]').innerText(), /not available/);
    assert.deepEqual(errors, []);
    await browser.close();
    console.log('PASS: five-step flow, validation, totals, safe rendering, WhatsApp encoding, mobile layout, reset, GPS, stale callbacks, empty data.');
})().catch(err => { console.error(err); process.exit(1); });
