<?php
/** Export public local service content and packages for the next theme deployment. */
if ( PHP_SAPI !== 'cli' ) exit;
require dirname( __DIR__, 4 ) . '/wp-load.php';
$entries = [];
$directory = nsp_service_directory();
foreach ( get_posts( [ 'post_type'=>'service', 'post_status'=>'publish', 'numberposts'=>-1, 'orderby'=>'menu_order title', 'order'=>'ASC' ] ) as $post ) {
    $title = html_entity_decode( $post->post_title, ENT_QUOTES, 'UTF-8' );
    $aliases = [];
    foreach ( $directory as $definition ) {
        if ( $definition['title'] === $title && ! empty( $definition['previous_title'] ) ) $aliases[] = $definition['previous_title'];
    }
    $terms = wp_get_object_terms( $post->ID, 'service_category' );
    if ( is_wp_error( $terms ) ) throw new RuntimeException( $terms->get_error_message() );
    $meta = [];
    foreach ( [ '_nsp_service_short_desc', '_nsp_service_features', '_nsp_price_basis' ] as $key ) {
        if ( metadata_exists( 'post', $post->ID, $key ) ) $meta[$key] = get_post_meta( $post->ID, $key, true );
    }
    $meta['_nsp_booking_packages'] = nsp_booking_packages( $post->ID );
    $entries[] = [
        'key'=>$post->post_name, 'title'=>$title, 'aliases'=>$aliases,
        'slug'=>$post->post_name, 'content'=>$post->post_content,
        'excerpt'=>$post->post_excerpt, 'order'=>(int)$post->menu_order, 'meta'=>$meta,
        'categories'=>array_map( static function ( $term ) { return [ 'name'=>$term->name, 'slug'=>$term->slug ]; }, $terms ),
    ];
}
// No environment-specific URLs, database IDs, attachments or customer information.
$json = wp_json_encode( $entries, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES );
$json = str_replace( [ NSP_THEME_URI, home_url() ], [ '{{theme_url}}', '{{site_url}}' ], $json );
$entries = json_decode( $json, true );
if ( ! is_array( $entries ) || ! $entries ) throw new RuntimeException( 'No published services to export.' );
$version = '1-' . hash( 'sha256', $json );
$output = "<?php\n/** Generated by tools/export-service-catalog.php; public business content only. */\nif ( ! defined( 'ABSPATH' ) ) exit;\nconst NSP_SERVICE_CATALOG_SEED_VERSION = " . var_export( $version, true ) . ";\nfunction nsp_deployment_service_seed(): array {\n    return " . var_export( $entries, true ) . ";\n}\n";
$file = NSP_THEME_DIR . '/inc/service-catalog-seed.php';
if ( false === file_put_contents( $file, $output ) ) throw new RuntimeException( 'Could not write the service snapshot.' );
echo 'Exported ', count( $entries ), ' published services with saved categories, descriptions, pricing modes and packages.', PHP_EOL;
